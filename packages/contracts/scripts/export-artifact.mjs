// Exports compiled contracts (abi + creation bytecode) as typed TS modules for the SDK and tests.
// Run after `forge build`. CI re-runs both and fails if generated/ is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const lowerFirst = (s) => s[0].toLowerCase() + s.slice(1);
for (const name of ["CosignerEnforcer", "X402Vault"]) {
  const art = JSON.parse(readFileSync(resolve(root, `out/${name}.sol/${name}.json`), "utf8"));
  const id = lowerFirst(name);
  const out = `// GENERATED by scripts/export-artifact.mjs from src/${name}.sol. Do not edit.
// solc 0.8.23, optimizer 200, evm london, no metadata hash (reproducible → stable CREATE2 address).
export const ${id}Abi = ${JSON.stringify(art.abi, null, 2)} as const;

export const ${id}Bytecode = "${art.bytecode.object}" as const;
`;
  writeFileSync(resolve(root, `generated/${name}.ts`), out);
  console.log(`wrote generated/${name}.ts (${(art.bytecode.object.length - 2) / 2} bytes initcode)`);
}
