// Exports the compiled CosignerEnforcer (abi + creation bytecode) as a typed TS module for the SDK.
// Run after `forge build`. CI re-runs both and fails if generated/ is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const art = JSON.parse(readFileSync(resolve(root, "out/CosignerEnforcer.sol/CosignerEnforcer.json"), "utf8"));
const out = `// GENERATED by scripts/export-artifact.mjs from src/CosignerEnforcer.sol. Do not edit.
// solc 0.8.23, optimizer 200, evm london, no metadata hash (reproducible → stable CREATE2 address).
export const cosignerEnforcerAbi = ${JSON.stringify(art.abi, null, 2)} as const;

export const cosignerEnforcerBytecode = "${art.bytecode.object}" as const;
`;
writeFileSync(resolve(root, "generated/CosignerEnforcer.ts"), out);
console.log(`wrote generated/CosignerEnforcer.ts (${(art.bytecode.object.length - 2) / 2} bytes initcode)`);
